        assert type(proof['optimizer_writes_per_rank']) is int and proof['optimizer_writes_per_rank']==20
        assert proof['ranks']==list(range(8)) and all(type(rank) is int for rank in proof['ranks'])
        structural=proof['structural']
        assert structural['role']=='policy_safety_calibration_structural_verification' and structural['execution_role']==plan['role']
        assert structural['run_id']==current['run_id'] and structural['calibration_sha256']==sha
        assert structural['outer_count']==1 and structural['optimizer_writes_per_rank']==20
        assert len(structural['global_monitors'])==40 and structural['production_admission'] is False
