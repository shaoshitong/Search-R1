def execution_role(run):
    role=run.get('policy_calibration_role','production')
    assert role in ('production',)+CALIBRATION_ROLES, 'Unknown policy execution role; never fall back to production'
    if has_formal_markers(run):assert_formal_run(run)
    return role


def adoption_inputs(run,base=None):
    """Require explicit source directories; their actual proofs are checked later."""
    role=execution_role(run)
    if role=='production' and run.get('contract_kind')==CONTRACT_KIND:
        # Only the exact new contract can omit external diagnostic sources.
        assert_formal_run(run)
        assert run['policy_safety_mode']==SAFETY_MODE
        return {}
    if role==CALIBRATION_ROLES[0]:return {}
    names=['policy_calibration_discovery_base']
    formal=role=='production' and run.get('contract_kind')==CONTRACT_KIND
    if role=='production' and not formal:names.append('policy_calibration_confirmation_base')
    sources={}
    for name in names:
        value=run.get(name)
        if not isinstance(value,str) or not value or any(c in value for c in '\r\n\0'):
            raise RuntimeError('Authenticated initial-probe adoption requires explicit '+name)
        path=Path(value)
        if not path.is_absolute() or str(path.resolve())!=value or not path.is_dir():
            raise RuntimeError('Authenticated initial-probe adoption requires a canonical existing '+name)
        sources[name]=path
    directories=list(sources.values())+([] if base is None else [Path(base).resolve()])
    if len(directories)!=len(set(directories)):
        raise RuntimeError('Authenticated initial-probe adoption requires distinct target/discovery/confirmation bases')
    if formal:
        assert_formal_run(run)
        for name in ('diagnostic_proof','diagnostic_terminal_proof'):
            value=run.get(name)
            if not isinstance(value,str) or not value or any(c in value for c in '\r\n\0'):
                raise RuntimeError('Authenticated initial-probe adoption requires explicit '+name)
            path=Path(value)
            if not path.is_absolute() or str(path.resolve())!=value or not path.is_file():
                raise RuntimeError('Authenticated initial-probe adoption requires a canonical existing '+name)
            sources[name]=path
    return sources


def supported_execution_role(run,base=None):
    role=execution_role(run)
    adoption_inputs(run,base)
    return role


def assert_initial_state(run):
    """Accept a bound native4 Easy boundary without resetting its real counters."""
    assert run['profile']=='common8' and run['completed_updates']==0
    assert run.get('restore_only_role') is None, 'Restore-only execution uses its independent entry'
    restore=run.get('full_state_restore') or {}
    if restore.get('kind')=='dynrpo7b_native4':
        from reproduction.dynrpo7b.infra_profile import native4
        assert native4(run) and 1 <= restore['completed_outer'] <= 200
        assert run['initial_probe_version']==restore['reward_probe_version']
        return
    if restore.get('kind')=='easy2560_native4':
        from reproduction.common8.precision_contract import easy2560_native4
        assert easy2560_native4(run) and type(restore['completed_outer']) is int and 1 <= restore['completed_outer'] < 200
        assert isinstance(restore['reward_probe_version'],str) and restore['reward_probe_version']
        assert run['initial_probe_version']==restore['reward_probe_version']
        return
    assert run['initial_probe_version'] is None


def request_interrupt(sig,frame):
    # Never raise asynchronously between Popen and durable ownership registration.
    global _interrupt_requested
    _interrupt_requested=sig


def gpu_rows(fields,kind='gpu'):
    # Operational query bound, not an occupancy/sampling-gap acceptance limit.
    return list(csv.reader(io.StringIO(subprocess.check_output(['nvidia-smi','--query-'+kind+'='+fields,'--format=csv,noheader,nounits'],text=True,timeout=30))))


