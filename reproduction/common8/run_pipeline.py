    def stage(self,name,**extra):publish(self.base/'logs/pipeline-status.json',dict(run_id=self.run['run_id'],stage=name,unix=time.time(),**extra))
    def sample(self):
        path=self.base/'logs'/('gpu-samples-'+self.run['run_id']+'.jsonl')
        try:
            from reproduction.a800.owned_processes import identity
            from reproduction.common8.policy_calibration_plan import canonical_bytes
            producer=identity(os.getpid())
            producer={key:producer[key] for key in ('pid','start_ticks','sid','uid')}
            source_sha=hashlib.sha256(canonical_bytes(self.run['source_sha256'])).hexdigest()
            with path.open('a') as f:
                while not self.stop_sampling.is_set():
                    rows=[];query_started=time.time()
                    for r in gpu_rows('index,uuid,memory.used,memory.total,utilization.gpu'):
                        if int(r[0]) in self.physical_indices:
                            item=dict(index=int(r[0]),uuid=r[1].strip(),used_mib=int(r[2]),total_mib=int(r[3]),util_percent=int(r[4]));rows.append(item)
                            self.max_used[item['index']]=max(self.max_used.get(item['index'],0),item['used_mib'])
                    sample=dict(schema_version=1,role='actual_common8_gpu_occupancy',
                        run_id=self.run['run_id'],slurm_job_id=self.job_id,
                        source_map_sha256=source_sha,sampler_identity=producer,sampling_interval_seconds=2,
                        query_started_unix=query_started,unix=time.time(),gpus=rows)
                    if self.local:sample.update(execution_backend='ssh_local',execution_id=self.run['execution_id'],
                        host=socket.gethostname(),hostname=socket.gethostname(),training_physical_indices=self.run['training_physical_indices'],
                        auxiliary_physical_indices=self.run['auxiliary_physical_indices'])
                    f.write(json.dumps(sample)+'\n');f.flush()
                    os.fsync(f.fileno())
                    parent_fd=os.open(path.parent,os.O_RDONLY|getattr(os,'O_DIRECTORY',0))
                    try:os.fsync(parent_fd)
                    finally:os.close(parent_fd)
                    self.stop_sampling.wait(2)
        except Exception as e:self.sample_error=repr(e)
    def finish_sampling(self,sampler):
        self.stop_sampling.set()
        if sampler is not None:sampler.join(35)  # nvidia-smi queries have a30s bound.
        if (sampler is not None and sampler.is_alive()) or self.sample_error is not None:
            reason='GPU sampling did not finish durably: '+str(self.sample_error)
            self.stage('FAILED',error=reason)
            raise RuntimeError(reason)

    def start(self,name,args,gpus,extra=None):
        assert _interrupt_requested is None, 'Pipeline stop requested before component launch'
        assert set(gpus)<=set(self.allowed), 'Component requested an unassigned GPU'
        assert 'CUDA_VISIBLE_DEVICES' not in (extra or {}), 'Component cannot bypass its assigned GPU subset'
        env=dict(self.env,CUDA_VISIBLE_DEVICES=','.join(self.device_tokens[i] for i in gpus));env.update(extra or {})
        process=self.owned.start(name,args,env,self.base/'logs'/(name+'.log'),self.repo)
        self.observe_all() # Deferred stop can now safely clean this registered child.
        return process
    def observe_all(self):
        for name,job in self.owned.jobs.items():
            if job['state']!='STOPPED':self.owned.observe(name)
        assert _interrupt_requested is None, 'Pipeline interrupted; clean up registered owned processes'
        assert self.sample_error is None, 'GPU sampling failed: '+str(self.sample_error)
    def wait(self,name,process,timeout=None):
        started=time.monotonic()
        while True:
            self.observe_all() # before poll can reap a session leader
            code=process.poll()
            if code is not None:
                self.owned.jobs[name]['exit_code']=code;self.owned.save()
                assert code==0, name+' failed; see project log'
                assert not self.owned.observe(name), name+' left owned subprocesses'
                self.owned.jobs[name]['state']='STOPPED';self.owned.save()
                return
            if timeout:assert time.monotonic()-started<timeout, name+' exceeded admission timeout'
            time.sleep(1)
    def endpoint(self,name,process,path,method='get',payload=None):
        import requests
        session=requests.Session();session.trust_env=False;started=time.monotonic()
        while True:
            self.observe_all();assert process.poll() is None, name+' exited during endpoint readiness'
            try:
                response=session.request(method,'http://127.0.0.1:'+path,json=payload,timeout=10);response.raise_for_status();return response.json()
            except requests.RequestException:
                assert time.monotonic()-started<1800, name+' endpoint readiness failed'
                time.sleep(2)
