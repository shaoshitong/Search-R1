        self.assertEqual((result['selected_mixed'],result['selected_all_correct_fallback']),(400,112))
        self.assertEqual(result['native_requests'],5120);self.assertEqual(result['included_actor_tokens'],5120)
        self.assertTrue(result['gate_row_tensor_hashes_rebuilt']);self.assertFalse(result['unselected_raw_required'])
        self.assertFalse(result['saved_strict_labels_recomputed_from_raw']);self.assertNotIn('full_training_history_verified',result)
        self.assertFalse(list(self.base.rglob('*.pt')))
        self.assertEqual(before,{p:hashlib.sha256(p.read_bytes()).hexdigest() for p in self.base.rglob('*') if p.is_file()})
        self.assertLess(len(json.dumps(result)),6000)

