def rebuild_native_hashes(trace, gate):
    bindings = {'expected_'+key:trace[key] for key in ('run_id','source_sha256','slurm_job_id','logical_update',
                'parent_group_ids','policy_snapshot_id','sampling')}
    bindings['expected_trajectory_ids'] = gate['trajectory_ids']
    projected = bt.project_sampling_logprobs(trace,**bindings); audit=projected['audit']
    gate.update(actor_rows_sha256=audit['actor_rows_sha256'],audit_sha256=bt.document_sha256(audit),
        actor_token_counts=audit['actor_token_counts'],included_actor_token_count=audit['included_token_count'])
    rows=trace['actor_rows']; dtype=gate['sampling_dtype']; values=projected['sampling_log_probs']
    width=len(values[0]); count=len(values)
    gate['tensor_sha256'] = {name:native_tensor_hash(Storage(data,kind,[count,width])) for name,data,kind in
        (('sampling_log_probs',values,dtype),('actor_mask',[r['info_mask'][r['prompt_width']:] for r in rows],'torch.int64'),
         ('attention_mask',[r['attention_mask'][r['prompt_width']:] for r in rows],'torch.int64'))}
    tensors={key:Storage([row[key] for row in rows],'torch.int64') for key in
             ('input_ids','attention_mask','position_ids','info_mask')}
    tensors.update(responses=Storage([row['input_ids'][row['prompt_width']:] for row in rows],'torch.int64'),
        old_log_probs=Storage(values,dtype),sampling_log_probs=Storage(values,dtype),
        sampling_mask=Storage(projected['sampling_mask'],'torch.bool'))
    batch=SimpleNamespace(batch=tensors)
    gate['row_tensor_sha256']={row['trajectory_id']:native_row_hash(batch,index) for index,row in enumerate(rows)}


class SelectionEvidenceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls): cls.documents=fixture_documents()
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory();self.base=Path(self.temp.name).resolve()
        self.run,self.update,self.audit,self.gate,self.trace,self.job=copy.deepcopy(self.documents)
        self.publish(rebuild=True)
    def tearDown(self): self.temp.cleanup()
    def write(self, relative, value):
        path=self.base/relative;path.parent.mkdir(parents=True,exist_ok=True)
        raw=bt.canonical_bytes(value);path.write_bytes(raw);return hashlib.sha256(raw).hexdigest()
    def publish(self, *, rebuild=False):
        aid=self.update['attempt_id']; self.audit['pool_path']=str(self.base/'artifacts/mixed-candidate-pools'/
            (aid+'-pool-'+str(self.audit['pool_retry'])))
        if rebuild: rebuild_native_hashes(self.trace,self.gate)
        sha=self.write('artifacts/behavior-traces/attempt-'+aid+'.json',self.trace)
        self.gate.update(trace_sha256=sha,private_trace_sha256=sha);self.update['behavior_trace_sha256']=sha
        self.update['behavior_probability_gate_sha256']=self.write('logs/behavior-probability-attempt-'+aid+'.json',self.gate)
        self.write('artifacts/mixed-selection/'+aid+'.json',self.audit)
    def verify(self): return core.verify_attempt(self.base,self.run,self.update,expected_job=self.job)
    def fails(self, pattern):
        with self.assertRaisesRegex(ValueError,pattern): self.verify()

    def test_complete_fallback_and_original_inputs_are_read_only_without_unselected_raw(self):
        before={p:hashlib.sha256(p.read_bytes()).hexdigest() for p in self.base.rglob('*') if p.is_file()}
        result=self.verify()
