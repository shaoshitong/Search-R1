class Storage:
    """A CPU fixture for just the production hash functions' tensor interface."""
    def __init__(self, values, dtype, shape=None):
        self.values, self.dtype = values, dtype
        self.shape = shape or [len(values)]
    def detach(self): return self
    def cpu(self): return self
    def contiguous(self): return self
    def view(self, dtype): return self
    def numpy(self): return self
    def __getitem__(self, index): return Storage(self.values[index], self.dtype)
    def tobytes(self):
        values = self.values if len(self.shape) == 1 else [v for row in self.values for v in row]
        code = {'torch.int64': 'q', 'torch.bool': 'B', 'torch.float32': 'f', 'torch.float64': 'd'}[self.dtype]
        result = array.array(code, values)
        if sys.byteorder != 'little': result.byteswap()
        return result.tobytes()


def native_hash_functions():
    """Execute the real native hash definitions, without importing their modules."""
    relative = 'reproduction/common8/behavior_runtime.py'
    tree = ast.parse((ROOT/relative).read_text())
    nodes = [node for node in tree.body if isinstance(node, ast.FunctionDef) and
             node.name in ('_tensor_hash', 'row_hash')]
    namespace = dict(hashlib=hashlib, canonical_bytes=bt.canonical_bytes,
                     document_sha256=bt.document_sha256, torch=SimpleNamespace(uint8='byte-view-fixture'))
    exec(compile(ast.Module(body=nodes, type_ignores=[]), relative, 'exec'), namespace)
    return namespace['_tensor_hash'], namespace['row_hash']


native_tensor_hash, native_row_hash = native_hash_functions()


